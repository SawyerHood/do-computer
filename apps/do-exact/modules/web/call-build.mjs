// Bundle the shared caller, not a second implementation of call events or handoffs.
const built = await Bun.build({ entrypoints: [new URL('./call-source.js', import.meta.url).pathname], target: 'browser', format: 'esm', minify: true });
if (!built.success) throw new AggregateError(built.logs, 'Call bundle failed');
const text = '// Generated by call-build.mjs; do not edit.\n' + await built.outputs[0].text();
const file = new URL('./call-core.js', import.meta.url);
if (process.argv.includes('--check')) { if (text !== await Bun.file(file).text()) throw new Error('call-core.js is stale'); }
else await Bun.write(file, text);

const media = await Bun.build({ entrypoints: [new URL('./call-media.ts', import.meta.url).pathname], target: 'browser', format: 'esm' });
if (!media.success) throw new AggregateError(media.logs, 'Call media build failed');
const mediaText = '// Generated by call-build.mjs; do not edit.\n' + await media.outputs[0].text();
const mediaFile = new URL('./call-media.js', import.meta.url);
if (process.argv.includes('--check')) { if (mediaText !== await Bun.file(mediaFile).text()) throw new Error('call-media.js is stale'); }
else await Bun.write(mediaFile, mediaText);
