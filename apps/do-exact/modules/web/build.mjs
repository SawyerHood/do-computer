// Run with Bun after pnpm install. Keep the output so a fresh Exact build needs no extra step.
// Bun's split-module identities depend on its working directory.
process.chdir(import.meta.dir);
const result = await Bun.build({
  entrypoints: [new URL('./engine-source.js', import.meta.url).pathname],
  target: 'browser', format: 'esm', minify: true,
});
if (!result.success) throw new AggregateError(result.logs, 'Mascot bundle failed');
const licenses = await Promise.all([
  Bun.file(new URL('../../../web/node_modules/three/LICENSE', import.meta.url)).text(),
  Bun.file(new URL('../../../../LICENSE', import.meta.url)).text(),
]);
const text = '// Generated by build.mjs; do not edit.\n/*\n' + licenses.join('\n\n') + '\n*/\n' + await result.outputs[0].text();
const file = new URL('./engine.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (text !== await Bun.file(file).text()) throw new Error('engine.js is stale; run bun modules/web/build.mjs');
} else await Bun.write(file, text);

// Split foreign content so a prose reply asks for neither Shiki nor Mermaid.
import { createRequire } from 'node:module';
import { readdirSync, rmSync, mkdirSync, realpathSync } from 'node:fs';
import { basename } from 'node:path';
const require = createRequire(realpathSync(new URL('../../../web/node_modules/react-markdown/index.js', import.meta.url)));
const folder = new URL('./markdown-built/', import.meta.url);
const content = await Bun.build({
  entrypoints: ['markdown', 'highlight', 'diagram'].map(name => new URL(`./${name}-source.js`, import.meta.url).pathname),
  target: 'browser', format: 'esm', minify: true, splitting: true,
  naming: { entry: '[name].js', chunk: 'chunk-[hash].js', asset: '[name]-[hash].[ext]' },
  root: new URL('./', import.meta.url).pathname,
  plugins: [{ name: 'markdown-dependencies', setup(build) {
    // These three are ReactMarkdown's dependencies, not new versions of its parser.
    build.onResolve({ filter: /^(unified|remark-parse|remark-rehype)$/ }, ({ path }) => ({ path: require.resolve(path) }));
  } }],
});
if (!content.success) throw new AggregateError(content.logs, 'Markdown bundles failed');
const theme = (await Bun.file(new URL('../../../web/src/theme-tokens.css', import.meta.url)).text())
  .replace(':root {', '.md {').replace('.dark {', '.md.dark {');
const outputs = new Map(await Promise.all(content.outputs.map(async output => [basename(output.path), '// Generated by build.mjs; do not edit.\n' + await output.text()])));
// GitHub's alert kinds wear the React app's Phosphor icons (components/markdown/markdown.tsx), filled.
const phosphor = createRequire(realpathSync(new URL('../../../web/package.json', import.meta.url))).resolve('@phosphor-icons/react');
const alertIcons = Object.fromEntries(await Promise.all(Object.entries({ note: 'Info', tip: 'Lightbulb', important: 'SealWarning', warning: 'Warning', caution: 'WarningOctagon' })
  .map(async ([kind, name]) => {
    const source = await Bun.file(new URL(`../dist/defs/${name}.es.js`, `file://${phosphor}`)).text();
    const fill = source.split('"fill"')[1]?.split(']')[0] ?? '';
    const paths = [...fill.matchAll(/d: "([^"]+)"/g)].map(m => m[1]);
    if (paths.length === 0) throw new Error(`${name}: no fill path`);
    return [kind, paths];
  })));
outputs.set('alert-icons.js', '// Generated by build.mjs; do not edit.\nexport default ' + JSON.stringify(alertIcons) + ';\n');
outputs.set('theme.js', '// Generated by build.mjs; do not edit.\nexport default ' + JSON.stringify(theme) + ';\n');
const { notices } = await import('./content-licenses.mjs');
outputs.set('NOTICE.txt', notices());
if (process.argv.includes('--check')) {
  const files = readdirSync(folder).sort();
  if (JSON.stringify(files) !== JSON.stringify([...outputs.keys()].sort())) throw new Error('Markdown bundle file list is stale');
  for (const [name, data] of outputs) if (data !== await Bun.file(new URL(name, folder)).text()) throw new Error(`${name} is stale; run bun modules/web/build.mjs`);
} else {
  rmSync(folder, { recursive: true, force: true }); mkdirSync(folder, { recursive: true });
  for (const [name, data] of outputs) await Bun.write(new URL(name, folder), data);
}
console.log(`Markdown: ${outputs.size} files, ${[...outputs.values()].reduce((n, s) => n + Buffer.byteLength(s), 0)} bytes; grammars and diagrams load on demand.`);
