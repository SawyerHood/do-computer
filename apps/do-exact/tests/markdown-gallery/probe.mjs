// Run while this gallery's ./x agent holds the web host. This reads the otherwise opaque DOM.
import { chromium } from '../../../web/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const done = new URL('./.exact/probe.done', import.meta.url);
const browser = await chromium.launch({ executablePath: process.env.CHROME, headless: true, args: ['--no-sandbox'] });
const checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const failures = [], requested = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => { if (request.url().includes('example.invalid')) requested.push(request.url()); });
  await page.route('https://example.invalid/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="60"><rect width="120" height="60" fill="teal"/><text x="10" y="35" fill="white">A picture</text></svg>' }));
  await page.goto('http://127.0.0.1:8766');
  const rich = page.locator('do-markdown').first();
  await rich.locator('.code pre code span').first().waitFor();
  await rich.locator('.diagram svg').waitFor();
  checks.push('Shiki tokens and completed Mermaid SVG load');
  assert.equal(await rich.locator('.table table').count(), 1);
  assert.equal(await rich.locator('.table td code .code').count(), 0);
  assert.equal(await rich.locator('th').last().getAttribute('align'), 'right');
  const bounds = await rich.evaluate(host => {
    const box = host.getBoundingClientRect(), body = host.shadowRoot.querySelector('.md').getBoundingClientRect();
    const scroll = host.shadowRoot.querySelector('pre');
    return { height: box.height, innerHeight: body.height, width: box.width, scrollWidth: scroll.scrollWidth, clientWidth: scroll.clientWidth, pageWidth: document.documentElement.scrollWidth };
  });
  assert(bounds.height > 300 && Math.abs(bounds.height - bounds.innerHeight) < 1);
  assert(bounds.width <= 390 && bounds.pageWidth <= 390);
  assert(bounds.scrollWidth > bounds.clientWidth);
  checks.push('natural height includes the diagram; code scrolls without widening the phone');
  const selection = await rich.evaluate(host => {
    const body = host.shadowRoot.querySelector('.md'), range = document.createRange();
    range.setStart(body.querySelector('p').firstChild, 0); range.setEndAfter(body.querySelector('code').lastChild);
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range);
    return selection.toString();
  });
  assert(selection.includes('closed block') && selection.includes('const'));
  checks.push('selection crosses prose and code inside the message');
  await rich.getByRole('button', { name: 'Copy code', exact: true }).first().click();
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('const greeting'));
  assert.equal(await page.locator('[data-testid="last"]').textContent(), 'copied');
  await rich.getByRole('button', { name: 'Wrap long lines', exact: true }).first().click();
  assert.equal(await rich.locator('pre.wrap').count(), 1);
  await rich.getByRole('button', { name: 'Copy as CSV' }).click();
  assert((await page.evaluate(() => navigator.clipboard.readText())).startsWith('Name,State,'));
  await rich.getByRole('button', { name: 'Copy as Markdown' }).click();
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('| Name |'));
  checks.push('code copy emits copied; wrap, Markdown copy and CSV copy work');
  const prose = page.locator('do-markdown').nth(1);
  assert.equal(await prose.locator('script,iframe,style[onload]').count(), 0);
  assert.equal(await prose.locator('a[href^="javascript:"]').count(), 0);
  assert.equal(await prose.locator('.alert[data-alert="tip"]').count(), 1);
  assert.equal(await prose.locator('input[type="checkbox"]').count(), 2);
  assert.equal(await prose.getByRole('heading', { name: 'Setext heading', exact: true }).count(), 1);
  assert.equal(await prose.locator('a[href="https://example.com"]').first().getAttribute('target'), '_blank');
  await prose.locator('summary').click();
  assert(await prose.locator('kbd').first().isVisible());
  assert.equal(await prose.locator('details').getAttribute('open'), '');
  assert.equal(requested.length, 0);
  await prose.getByRole('button', { name: 'Show', exact: true }).click();
  await prose.locator('img').waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('do-markdown')].some(host => [...host.shadowRoot.querySelectorAll('img')].some(img => img.complete && img.naturalWidth > 0)));
  assert.equal(requested.length, 1);
  checks.push('sanitization, GFM tasks, reference links, alerts, folding HTML and image consent work');
  // Change props through the host ABI, as Contract does, to isolate async replacement races.
  const set = (host, props) => host.setAttribute('data-nativeviewprops', JSON.stringify(props));
  await rich.evaluate(set, { text: '# Local heading\n\n[Go](#local-heading)\n\n[File](notes/hello.md)', files: '[{"path":"notes/hello.md","id":"hello"}]' });
  await rich.locator('h1').waitFor();
  await rich.getByRole('link', { name: 'Go', exact: true }).click();
  assert.equal(new URL(page.url()).hash, '');
  await rich.getByRole('link', { name: 'File', exact: true }).click();
  assert.equal(await page.locator('[data-testid="last"]').textContent(), 'file:hello');
  checks.push('heading links stay within the reply; resolved library links emit file:id');
  const streamed = page.locator('do-code').first();
  await streamed.evaluate(set, { code: 'const first = 1;', language: 'ts', streaming: 'true' });
  await streamed.locator('code').filter({ hasText: 'const first' }).waitFor();
  assert.equal(await streamed.locator('code span').count(), 0);
  await streamed.evaluate(host => {
    host.retained = host.shadowRoot.querySelector('code').firstChild;
    const range = document.createRange(); range.setStart(host.retained, 0); range.setEnd(host.retained, 5);
    getSelection().removeAllRanges(); getSelection().addRange(range);
  });
  await streamed.evaluate(set, { code: 'const first = 1;\nconst second = 2;', language: 'ts', streaming: 'true' });
  await streamed.locator('code').filter({ hasText: 'second' }).waitFor();
  assert.equal(await streamed.evaluate(host => host.retained === host.shadowRoot.querySelector('code').firstChild && getSelection().toString() === 'const'), true);
  const before = await streamed.evaluate(host => host.getBoundingClientRect().height);
  await streamed.evaluate(set, { code: 'const first = 1;\nconst second = 2;', language: 'ts', streaming: 'false' });
  await streamed.locator('code span').first().waitFor();
  const after = await streamed.evaluate(host => host.getBoundingClientRect().height);
  assert.equal(before, after);
  checks.push('streaming keeps the text node and selection; final highlighting does not change height');
  // A malformed complete diagram is readable code, and a later valid one recovers.
  const diagram = page.locator('do-mermaid').first();
  await diagram.evaluate(set, { diagram: 'flowchart LR\n A[unfinished', streaming: 'false' });
  await diagram.locator('pre:not([hidden])').waitFor();
  assert((await diagram.locator('code').textContent()).includes('unfinished'));
  await diagram.evaluate(set, { diagram: 'flowchart LR\n A --> B', dark: 'true' });
  await diagram.locator('.diagram svg').waitFor();
  await diagram.getByRole('button', { name: 'Show the code', exact: true }).click();
  assert(await diagram.locator('pre').isVisible());
  await diagram.getByRole('button', { name: 'Show the diagram', exact: true }).click();
  assert(await diagram.locator('.diagram').isVisible());
  checks.push('invalid Mermaid falls back, recovers, switches to source and back');
  const errors = failures.filter(error => !error.includes('WebGL'));
  assert.deepEqual(errors, []);
  console.log(checks.map(name => `PASS ${name}`).join('\n'));
  console.log(`${checks.length} browser checks passed; no page errors`);
} finally {
  await browser.close(); writeFileSync(done, 'done');
}
