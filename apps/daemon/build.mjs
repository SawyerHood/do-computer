// Bundles the daemon into one CommonJS file, and writes it into the web app as a string so the
// server can hand it to `curl | sh`. The .cjs extension matters: a stray {"type":"module"}
// package.json in someone's home directory would otherwise make Node read the bundle as ESM.
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { build } from "esbuild"

const common = {
  entryPoints: ["src/main.ts"],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  banner: { js: "#!/usr/bin/env node" },
  minify: true,
  logLevel: "warning",
}

// The version is the hash of the bundle built without a version, so it changes exactly when
// the code does.
const draft = await build({ ...common, write: false, define: { DAEMON_VERSION: '"draft"' } })
const version = createHash("sha256").update(draft.outputFiles[0].text).digest("hex").slice(0, 12)
await build({
  ...common,
  outfile: "dist/daemon.cjs",
  define: { DAEMON_VERSION: JSON.stringify(version) },
})

const bundle = readFileSync("dist/daemon.cjs", "utf8")
const target = new URL("../web/src/server/daemon-bundle.generated.ts", import.meta.url)
mkdirSync(new URL(".", target), { recursive: true })
writeFileSync(
  target,
  `// Generated by apps/daemon/build.mjs. Do not edit; run \`pnpm --filter @durable-computer/daemon build\`.\n` +
    `export const DAEMON_VERSION = ${JSON.stringify(version)}\n` +
    // What a daemon that updates itself checks its download against.
    `export const DAEMON_SHA256 = ${JSON.stringify(createHash("sha256").update(bundle).digest("hex"))}\n` +
    `export const DAEMON_BUNDLE = ${JSON.stringify(bundle)}\n`,
)
console.log(`daemon ${version}: ${(bundle.length / 1024).toFixed(0)} KB`)
